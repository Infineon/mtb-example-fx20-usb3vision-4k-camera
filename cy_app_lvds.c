/*****************************************************************************
 * Function Name: Cy_LVDS_PhyEventCb
 *****************************************************************************
 * Description: GPIF error callback function.
 *
 * Parameters:
 * \param smNo
 * state machine number
 *
 * \param phyEvent
 * LVDS/LVCMOS PHY event
 *
 * \param cntxt
 * app context
 *
 * Return:
 *  void
 ****************************************************************************/
void Cy_LVDS_PhyEventCb(uint8_t smNo, cy_en_lvds_phy_events_t phyEvent, void *cntxt)
{
    APP_DBG_TRACE1("Cy_LVDS_PhyEventCb: sm_no= 0x%x, phy_event= 0x%x\r\n", smNo, phyEvent);
    if (phyEvent == CY_LVDS_PHY_TRAINING_DONE)
    {
        APP_DBG_TRACE("PORT%d PHY training completed\r\n", smNo);
        if (smNo)
        {
            lvdsTrainingStatus |= P1_PHY_TRAINING_DONE;
        }
        else
        {
            lvdsTrainingStatus |= P0_PHY_TRAINING_DONE;
        }
    }
    if (phyEvent == CY_LVDS_PHY_LNK_TRAIN_BLK_DET)
    {
        APP_DBG_TRACE("PORT%d Training Block Detected\r\n", smNo);
        if (smNo)
        {
            lvdsTrainingStatus |= P1_TRAINING_DONE;
        }
        else
        {
            lvdsTrainingStatus |= P0_TRAINING_DONE;
        }
    }
    if (phyEvent == CY_LVDS_PHY_LNK_TRAIN_BLK_DET_FAIL)
    {
        APP_DBG_ERR("PORT%d Training Block Detect Failed\r\n", smNo);
    }
    if (phyEvent == CY_LVDS_PHY_L1_EXIT)
    {
        APP_DBG_TRACE("P%d_L1_Exit\r\n", smNo);
    }
    if (phyEvent == CY_LVDS_PHY_L1_ENTRY)
    {
        APP_DBG_TRACE("P%d_L1_Entry\r\n", smNo);
    }
    if (phyEvent == CY_LVDS_PHY_L3_ENTRY)
    {
        APP_DBG_TRACE("P%d_L3_Entry\r\n", smNo);
    }
}

